# Let's write the generator function that builds all 45 questions for each day
def build_day(day_num):
    title, proverb, theme = DAY_METAS[day_num]
    ans = get_official_answers(day_num)
    
    if day_num == 9:
        questions = get_day9_questions(ans)
    else:
        # Build Day from raw text and question definitions
        questions = build_day_generic(day_num, ans)
        
    day_data = {
        "day": day_num,
        "title": title,
        "proverb": proverb,
        "description": theme,
        "totalQuestions": 45,
        "questions": questions
    }
    
    # Validation gate
    ok, errs = validate_n1_day(day_data)
    if not ok:
        raise ValueError(f"Day {day_num} failed validation: {errs}")
        
    # Save to 4 locations
    day_str = f"day{day_num:02d}.json"
    for dest in [
        f"data/n1_20days/{day_str}",
        f"public/data/n1_20days/{day_str}",
        f"data/{day_str}",
        f"public/data/{day_str}"
    ]:
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        with open(dest, "w", encoding="utf-8") as f:
            json.dump(day_data, f, ensure_ascii=False, indent=2)
            
    log(f"[SUCCESS] Day {day_num:02d} ({title}) generated, validated, and saved (45 Qs).")
    return day_data


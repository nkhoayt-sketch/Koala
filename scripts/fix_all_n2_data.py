def clean_trailing_garbage(text):
    if not isinstance(text, str):
        return text
    # Remove exam watermark like N2 07/2025 or N2 12/2023
    text = re.sub(r'\s*N2\s+\d{2}/\d{4}\b.*$', '', text, flags=re.DOTALL)
    # Remove leaked footer/header numbers
    text = re.sub(r'\s*\b\d+\s*$', '', text)
    return text.strip()


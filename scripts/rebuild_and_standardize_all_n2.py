def clean_furigana_text(text):
    if not isinstance(text, str):
        return text
    for pat, rep in FURIGANA_REPLACEMENTS:
        text = re.sub(pat, rep, text)
    text = re.sub(r'\s*N2\s+\d{1,2}/\d{4}.*$', '', text, flags=re.IGNORECASE)
    # Fix single kana between kanji: e.g. "休 きゅう 憩"
    text = re.sub(r'([^\x00-\x7F]) +([^\x00-\x7F])', r'\1\2', text)
    return text.strip()


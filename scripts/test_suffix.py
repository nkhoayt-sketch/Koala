import re

m9_sample = """
48 から 51 の中に入る最もよいものを、1・2・3・4 から一つ選びなさい。
以下は、留学生がスピーチのために書いた文章である。
紅葉の異変
サリム・ソフィア
私は日本の秋の景色が好きです。

 48a   
1   そこの紅葉 2   そんな紅葉 
3   そちら 4   紅葉 
 49a  
1   結局 2   確かに 
3   しかし 4   つまり   
 50 。    
1   始まらないのです 2   始まらないためです 
3   始まらないのでしょうか 4   始まらないためでしょうか 
 51 。    
1   感じているからだと思います 2   感じられるところだと思います 
3   感じさせることができました 4   感じるようになりました 
"""

for q in [48, 49, 50, 51]:
    m = re.search(rf'(?:^|\n)\s*{q}[^\d\n]?', m9_sample)
    print(f"Q{q} matched at:", m.start() if m else "None")
